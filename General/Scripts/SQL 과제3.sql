--13. 'Tokyo'시에서 근무중인 사원의 이름을 조회하시오.
SELECT FIRST_NAME 
	 , LAST_NAME 
  FROM EMPLOYEES
 WHERE EMPLOYEE_ID = (SELECT E.EMPLOYEE_ID 
 					    FROM EMPLOYEES E
 					   INNER JOIN DEPARTMENTS D
    					  ON E.DEPARTMENT_ID = D.DEPARTMENT_ID 
    				   INNER JOIN LOCATIONS L
    				      ON D.LOCATION_ID = L.LOCATION_ID 
    				     AND L.CITY = 'Tokyo')
;

--14. 'Kuwait'국가에서 근무중인 사원의 직무명을 중복없이 조회하시오.
SELECT DISTINCT J.JOB_TITLE  
  FROM EMPLOYEES E
 INNER JOIN JOBS J
    ON E.JOB_ID = J.JOB_ID 
 WHERE E.EMPLOYEE_ID IN (SELECT EMPLOYEE_ID
                           FROM EMPLOYEES E2
                           INNER JOIN DEPARTMENTS D
    						  ON E2.DEPARTMENT_ID = D.DEPARTMENT_ID 
 						   INNER JOIN LOCATIONS L
    						  ON D.LOCATION_ID = L.LOCATION_ID 
 						   INNER JOIN COUNTRIES C
      						  ON L.COUNTRY_ID = C.COUNTRY_ID 
  							 AND C.COUNTRY_NAME = 'Kuwait')
;